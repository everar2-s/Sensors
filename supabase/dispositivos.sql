-- Dispositivos registrados manualmente. Ejecutar en Supabase SQL Editor antes de usar el formulario.
create table if not exists public.dispositivos (
  id bigint generated by default as identity primary key,
  nombre text not null unique check (char_length(trim(nombre)) between 1 and 100),
  creado_en timestamptz not null default now()
);

alter table public.dispositivos enable row level security;

grant select, insert on public.dispositivos to authenticated;
grant usage, select on sequence public.dispositivos_id_seq to authenticated;

create policy "Los usuarios autenticados pueden consultar dispositivos"
on public.dispositivos for select to authenticated using (true);

create policy "Los usuarios autenticados pueden registrar dispositivos"
on public.dispositivos for insert to authenticated with check (true);

-- Relación: cada medición apunta al dispositivo por su identificador estable.
alter table public.mediciones
  add column if not exists dispositivo_id bigint references public.dispositivos(id);

-- Vincula las lecturas existentes cuyo texto coincide con el nombre registrado.
update public.mediciones as m
set dispositivo_id = d.id
from public.dispositivos as d
where m.dispositivo_id is null
  and m.dispositivo = d.nombre;

create index if not exists mediciones_dispositivo_id_idx
  on public.mediciones (dispositivo_id);

-- Vincula automáticamente inserts del firmware actual, que todavía envía `dispositivo`.
create or replace function public.vincular_medicion_con_dispositivo()
returns trigger
language plpgsql
as $$
begin
  if new.dispositivo_id is null and new.dispositivo is not null then
    select d.id into new.dispositivo_id
    from public.dispositivos as d
    where d.nombre = new.dispositivo;
  end if;
  return new;
end;
$$;

drop trigger if exists mediciones_vincular_dispositivo on public.mediciones;
create trigger mediciones_vincular_dispositivo
before insert or update of dispositivo, dispositivo_id on public.mediciones
for each row execute function public.vincular_medicion_con_dispositivo();
